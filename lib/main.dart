import 'package:flutter/material.dart';
import 'package:flutter_localizations/flutter_localizations.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:google_fonts/google_fonts.dart';
import 'package:intl/date_symbol_data_local.dart';
import 'l10n/app_localizations.dart';
import 'screens/home_screen.dart';
import 'services/locale_controller.dart';
import 'utils/constants.dart';
import 'firebase_options.dart';

void main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Loads the CLDR date-symbol data (weekday/month names, etc.) that
  // package:intl's DateFormat needs for locales other than English - without
  // this, formatting a date in Hindi throws until it's been called at least
  // once for that locale.
  await initializeDateFormatting();

  // firebase_options.dart now exists (generated by `flutterfire configure`),
  // so Firebase.initializeApp() is given explicit per-platform options
  // instead of relying on native config files alone. Kept in a try/catch
  // as defense-in-depth: if the Realtime Database/project setup is ever
  // incomplete, the app still falls back to sample data instead of
  // crashing before any UI appears - see README for full Firebase setup.
  try {
    await Firebase.initializeApp(
      options: DefaultFirebaseOptions.currentPlatform,
    );
    if (FirebaseAuth.instance.currentUser == null) {
      await FirebaseAuth.instance.signInAnonymously();
    }
  } catch (e) {
    debugPrint('Firebase unavailable, continuing without it: $e');
  }

  final localeController = LocaleController();
  await localeController.load();

  runApp(MosqueFinderApp(localeController: localeController));
}

class MosqueFinderApp extends StatelessWidget {
  final LocaleController localeController;

  const MosqueFinderApp({super.key, required this.localeController});

  @override
  Widget build(BuildContext context) {
    final textTheme = GoogleFonts.poppinsTextTheme().apply(
      bodyColor: AppColors.richBlack,
      displayColor: AppColors.richBlack,
    );

    // Rebuilds the whole app when the user changes language in Settings -
    // ListenableBuilder is enough here since there's no other app-wide state
    // to thread through, unlike a full state-management package.
    return ListenableBuilder(
      listenable: localeController,
      builder: (context, _) {
        return MaterialApp(
          onGenerateTitle: (context) => AppLocalizations.of(context)!.appTitle,
          debugShowCheckedModeBanner: false,
          locale: localeController.locale,
          supportedLocales: kSupportedLocales,
          localizationsDelegates: const [
            AppLocalizations.delegate,
            GlobalMaterialLocalizations.delegate,
            GlobalWidgetsLocalizations.delegate,
            GlobalCupertinoLocalizations.delegate,
          ],
          theme: ThemeData(
            useMaterial3: true,
            scaffoldBackgroundColor: AppColors.creamBackground,
            textTheme: textTheme,
            colorScheme: ColorScheme.fromSeed(
              seedColor: AppColors.mehndiGreen,
              brightness: Brightness.light,
              primary: AppColors.mehndiGreen,
              onPrimary: AppColors.richBlack,
              secondary: AppColors.lightGold,
              onSecondary: AppColors.richBlack,
              surface: Colors.white,
              onSurface: AppColors.richBlack,
            ),
            appBarTheme: AppBarTheme(
              backgroundColor: AppColors.mehndiGreen,
              foregroundColor: AppColors.richBlack,
              titleTextStyle: AppFonts.heading(
                fontSize: 21,
                fontWeight: FontWeight.w700,
                color: AppColors.richBlack,
              ),
            ),
            bottomNavigationBarTheme: const BottomNavigationBarThemeData(
              backgroundColor: Colors.white,
              selectedItemColor: AppColors.mehndiGreen,
              unselectedItemColor: AppColors.richBlack,
            ),
            elevatedButtonTheme: ElevatedButtonThemeData(
              style: ElevatedButton.styleFrom(
                backgroundColor: AppColors.mehndiGreen,
                foregroundColor: AppColors.richBlack,
              ),
            ),
            floatingActionButtonTheme: const FloatingActionButtonThemeData(
              backgroundColor: AppColors.lightGold,
              foregroundColor: AppColors.richBlack,
            ),
            cardTheme: const CardThemeData(
              color: Colors.white,
              surfaceTintColor: Colors.transparent,
            ),
          ),
          home: HomeScreen(localeController: localeController),
        );
      },
    );
  }
}
